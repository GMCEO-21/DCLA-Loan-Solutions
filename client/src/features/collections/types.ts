export interface Member {
  id: string;
  firstName: string;
  lastName: string;
  middleName: string;
  contactNumber: string;
  address: string;
  birthDate?: string;
  center?: Center;
  createdAt: string;
  updatedAt: string;
}

export interface MemberWithLoans extends Member {
  loans: Array<{
    id: string;
    amount: number;
    balance: number;
    status: string;
    dueDate: string;
    loanCreatedDate?: string;
    createdAt?: string;
    netCashReleased?: number;
    paymentCountDisplayOffset?: number;
  }>;
  totalLoanAmount: number;
  totalBalance: number;
  overallAmount?: number;
  weeklyPaymentAmount?: number;
  totalTermWeeks?: number;
  totalSavings?: number;
  netCashReleased?: number;
  netCashReleasedForDate?: number;
  numberOfPayments?: number;
  collection?: Collection;
  weeklyPaid?: boolean | null;
  weeklyHasAllocation?: boolean | null;
  weeklyAmountDue?: number | null;
  weeklyAmountApplied?: number | null;
  weeklyFinancial?: {
    kind:
      | "scheduled_week"
      | "post_maturity_no_weekly_obligation"
      | "pre_first_due_no_weekly_obligation"
      | "historical_funding_unavailable"
      | "missing_schedule_unexpectedly";
    amountDue: number | null;
    amountApplied: number | null;
    postMaturityLoanCount: number;
    incompleteScheduleLoanCount: number;
  };
  loanCondition?: {
    status: "normal" | "past_due" | "past_maturity" | "indeterminate";
  };
}

export interface Center {
  id: string;
  name: string;
  collectionDay: string;
  address?: string;
  createdAt: string;
  updatedAt: string;
}

export interface Collection {
  id: string;
  memberId: string;
  centerId: string;
  amount: number;
  netRelease: number;
  paymentReceived: number;
  collectionDate: string;
  notes?: string;
  isAutoGenerated: boolean;
  numberOfPayments?: number;
  advancePaymentAmount?: number;
  advancePaymentStatus?: "none" | "partial" | "full";
  member?: Member;
  center?: Center;
  createdAt: string;
  updatedAt: string;
}

export interface DailyCollectionGroup {
  centerId: string;
  centerName: string;
  collectionDay: string;
  collectionDate: string;
  totalAmount: number;
  totalReceived: number;
  totalMembers: number;
  pendingCollections: number;
  collections: Collection[];
}

