import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  JoinColumn,
  Unique,
} from 'typeorm';
import { Center } from '../../centers/entities/center.entity';
import { Member } from '../../members/entities/member.entity';

export enum AdvancePaymentStatus {
  NONE = 'none',
  PARTIAL = 'partial',
  FULL = 'full',
}

@Entity()
@Unique('UQ_collection_member_center_date', [
  'memberId',
  'centerId',
  'collectionDate',
])
export class Collection {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ type: 'date' })
  collectionDate: string;

  @Column({ type: 'decimal', precision: 12, scale: 2, default: 0 })
  amount: number;

  @Column({ type: 'decimal', precision: 12, scale: 2, default: 0 })
  netRelease: number;

  @Column({ type: 'decimal', precision: 12, scale: 2, default: 0 })
  paymentReceived: number;

  @Column({ type: 'text', nullable: true })
  notes: string;

  @Column({ type: 'boolean', default: false })
  isAutoGenerated: boolean;

  @Column({ type: 'int', default: 0 })
  numberOfPayments: number;

  @Column({ type: 'decimal', precision: 12, scale: 2, default: 0 })
  advancePaymentAmount: number;

  @Column({
    type: 'enum',
    enum: AdvancePaymentStatus,
    default: AdvancePaymentStatus.NONE,
  })
  advancePaymentStatus: AdvancePaymentStatus;

  @ManyToOne(() => Center, (center) => center.id, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'centerId' })
  center: Center;

  @Column()
  centerId: string;

  @ManyToOne(() => Member, (member) => member.id, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'memberId' })
  member: Member;

  @Column()
  memberId: string;

  @CreateDateColumn()
  createdAt: Date;

  @UpdateDateColumn()
  updatedAt: Date;
}
